import UIKit
import Flutter
import CoreBluetooth
import ExternalAccessory

@main
@objc class AppDelegate: FlutterAppDelegate {
  private let scanner = SolosIOSBleScanner()
  private let accessoryTransport = SolosIOSAccessoryTransport()
  private let emptyNotifications = SolosEmptyEventStream()

  override func application(
    _ application: UIApplication,
    didFinishLaunchingWithOptions launchOptions: [UIApplication.LaunchOptionsKey: Any]?
  ) -> Bool {
    GeneratedPluginRegistrant.register(with: self)

    guard let controller = window?.rootViewController as? FlutterViewController else {
      return super.application(application, didFinishLaunchingWithOptions: launchOptions)
    }
    let messenger = controller.binaryMessenger

    // Use the actual 428x240 image packets generated by Flutter, but only
    // when iOS exposes an approved ExternalAccessory/MFi data session.
    FlutterMethodChannel(name: "solos_rfcomm", binaryMessenger: messenger)
      .setMethodCallHandler { [weak self] call, result in
        guard let self = self else {
          result(FlutterError(code: "NO_TRANSPORT", message: "Accessory transport unavailable", details: nil))
          return
        }
        self.accessoryTransport.handle(call, result: result)
      }

    FlutterEventChannel(name: "solos_rfcomm_events", binaryMessenger: messenger)
      .setStreamHandler(accessoryTransport)

    FlutterMethodChannel(name: "solos_ios_accessories", binaryMessenger: messenger)
      .setMethodCallHandler { [weak self] call, result in
        guard let self = self else { result([]); return }
        if call.method == "list" {
          result(self.accessoryTransport.listedAccessories())
        } else {
          result(FlutterMethodNotImplemented)
        }
      }

    // Apple's sandbox does not allow reading other apps' notifications.
    FlutterEventChannel(name: "solos_notifications", binaryMessenger: messenger)
      .setStreamHandler(emptyNotifications)

    // Keep the existing Dart channel contract for platform URLs and settings.
    FlutterMethodChannel(name: "solos_intent", binaryMessenger: messenger)
      .setMethodCallHandler { call, result in
        switch call.method {
        case "getInitialIntent":
          result(nil)
        case "openUrl":
          guard let args = call.arguments as? [String: Any],
                let raw = args["url"] as? String,
                let url = URL(string: raw),
                let scheme = url.scheme?.lowercased(),
                ["https", "http", "maps", "comgooglemaps"].contains(scheme) else {
            result(FlutterError(code: "INVALID_URL", message: "Unsupported URL", details: nil))
            return
          }
          UIApplication.shared.open(url, options: [:]) { success in
            result(success)
          }
        case "openNotificationSettings":
          guard let url = URL(string: UIApplication.openSettingsURLString) else {
            result(false)
            return
          }
          UIApplication.shared.open(url, options: [:]) { success in
            result(success)
          }
        case "mediaPlayPause", "mediaNext", "mediaPrev", "volumeUp", "volumeDown",
             "launchAssistant", "launchPhoneAssistant":
          result(FlutterError(
            code: "IOS_PLATFORM_RESTRICTED",
            message: "This Android phone/media action is not available in the iOS companion.",
            details: nil
          ))
        default:
          result(FlutterMethodNotImplemented)
        }
      }

    FlutterMethodChannel(name: "solos_actions", binaryMessenger: messenger)
      .setMethodCallHandler { _, result in
        result(FlutterError(
          code: "IOS_NOTIFICATION_ACTIONS_UNAVAILABLE",
          message: "iOS does not provide notification action control for other apps.",
          details: nil
        ))
      }

    // Optional BLE diagnostics. This does not connect the HUD display.
    FlutterMethodChannel(name: "solos_ios_ble", binaryMessenger: messenger)
      .setMethodCallHandler { [weak self] call, result in
        guard let self = self else {
          result(FlutterError(code: "SCANNER_UNAVAILABLE", message: "Scanner unavailable", details: nil))
          return
        }
        switch call.method {
        case "scan":
          self.scanner.scan(result: result)
        case "stopScan":
          self.scanner.stop(result: result)
        default:
          result(FlutterMethodNotImplemented)
        }
      }

    return super.application(application, didFinishLaunchingWithOptions: launchOptions)
  }
}

private final class SolosEmptyEventStream: NSObject, FlutterStreamHandler {
  func onListen(withArguments arguments: Any?, eventSink events: @escaping FlutterEventSink) -> FlutterError? {
    return nil
  }

  func onCancel(withArguments arguments: Any?) -> FlutterError? {
    return nil
  }
}

/// Scans advertising BLE devices to help diagnose iOS compatibility.
/// This intentionally does not write Solos HUD packets to unknown BLE services.
private final class SolosIOSBleScanner: NSObject, CBCentralManagerDelegate {
  private var central: CBCentralManager?
  private var pending: FlutterResult?
  private var scanTimer: Timer?
  private var discovered: [UUID: [String: Any]] = [:]
  private var scanning = false

  func scan(result: @escaping FlutterResult) {
    guard pending == nil else {
      result(FlutterError(code: "SCAN_BUSY", message: "Bluetooth scan already running", details: nil))
      return
    }
    pending = result
    discovered.removeAll()
    scanning = false
    if central == nil {
      central = CBCentralManager(delegate: self, queue: .main)
    } else {
      centralManagerDidUpdateState(central!)
    }
  }

  func stop(result: @escaping FlutterResult) {
    let output = sortedDevices()
    finish()
    result(output)
  }

  func centralManagerDidUpdateState(_ central: CBCentralManager) {
    guard pending != nil else { return }
    switch central.state {
    case .poweredOn:
      guard !scanning else { return }
      scanning = true
      central.scanForPeripherals(withServices: nil,
                                 options: [CBCentralManagerScanOptionAllowDuplicatesKey: false])
      scanTimer?.invalidate()
      scanTimer = Timer.scheduledTimer(withTimeInterval: 8.0, repeats: false) { [weak self] _ in
        self?.finish()
      }
    case .unauthorized:
      fail("BLUETOOTH_PERMISSION_DENIED", "Allow Bluetooth access in iPhone Settings.")
    case .poweredOff:
      fail("BLUETOOTH_OFF", "Turn on Bluetooth in iPhone Settings.")
    case .unsupported:
      fail("BLUETOOTH_UNSUPPORTED", "This iPhone does not support Bluetooth LE.")
    case .resetting, .unknown:
      break // Wait for CoreBluetooth to finish initializing.
    @unknown default:
      fail("BLUETOOTH_UNKNOWN", "Unknown Bluetooth state.")
    }
  }

  func centralManager(_ central: CBCentralManager,
                      didDiscover peripheral: CBPeripheral,
                      advertisementData: [String: Any],
                      rssi RSSI: NSNumber) {
    let advertisedName = advertisementData[CBAdvertisementDataLocalNameKey] as? String
    let name = advertisedName ?? peripheral.name ?? "Unknown BLE device"
    let serviceUUIDs = (advertisementData[CBAdvertisementDataServiceUUIDsKey] as? [CBUUID]) ?? []
    discovered[peripheral.identifier] = [
      "id": peripheral.identifier.uuidString,
      "name": name,
      "rssi": RSSI.intValue,
      "services": serviceUUIDs.map { $0.uuidString },
      "isSolos": name.localizedCaseInsensitiveContains("solos")
    ]
  }

  private func sortedDevices() -> [[String: Any]] {
    return discovered.values.sorted { ($0["rssi"] as? Int ?? -200) > ($1["rssi"] as? Int ?? -200) }
  }

  private func finish() {
    central?.stopScan()
    scanTimer?.invalidate()
    scanTimer = nil
    scanning = false
    let callback = pending
    pending = nil
    callback?(sortedDevices())
  }

  private func fail(_ code: String, _ message: String) {
    central?.stopScan()
    scanTimer?.invalidate()
    scanTimer = nil
    scanning = false
    let callback = pending
    pending = nil
    callback?(FlutterError(code: code, message: message, details: nil))
  }
}

/// An optional iOS transport for the original display-equipped Solos eyewear.
/// The existing Dart HUD packet generator is used without modification.
///
/// Important: Bluetooth Settings pairing alone does not grant apps an RFCOMM
/// socket. This class works ONLY for an accessory exposed by Apple's MFi
/// ExternalAccessory API with a manufacturer-approved protocol identifier that
/// is also declared in UISupportedExternalAccessoryProtocols in Info.plist.
/// Do not substitute a guessed protocol string.
private final class SolosIOSAccessoryTransport: NSObject, FlutterStreamHandler, StreamDelegate {
  private final class PendingWrite {
    let data: Data
    var offset = 0
    let callback: FlutterResult
    init(data: Data, callback: @escaping FlutterResult) {
      self.data = data
      self.callback = callback
    }
  }

  private var session: EASession?
  private var connectedAccessory: EAAccessory?
  private var input: InputStream?
  private var output: OutputStream?
  private var sink: FlutterEventSink?
  private var pendingConnect: FlutterResult?
  private var rxBuffer = Data()
  private var outgoing: [PendingWrite] = []
  private var generation = 0

  override init() {
    super.init()
    EAAccessoryManager.shared().registerForLocalNotifications()
  }

  private var declaredProtocols: [String] {
    return Bundle.main.object(forInfoDictionaryKey: "UISupportedExternalAccessoryProtocols") as? [String] ?? []
  }

  private func candidates() -> [EAAccessory] {
    return EAAccessoryManager.shared().connectedAccessories.filter {
      $0.name.localizedCaseInsensitiveContains("solos") ||
      $0.manufacturer.localizedCaseInsensitiveContains("solos") ||
      $0.name.localizedCaseInsensitiveContains("kopin") ||
      $0.manufacturer.localizedCaseInsensitiveContains("kopin")
    }
  }

  private func usableProtocol(for device: EAAccessory) -> String? {
    return device.protocolStrings.first { declaredProtocols.contains($0) }
  }

  func listedAccessories() -> [[String: Any]] {
    return EAAccessoryManager.shared().connectedAccessories.map { device in
      [
        "name": device.name,
        "manufacturer": device.manufacturer,
        "model": device.modelNumber,
        "id": device.connectionID,
        "protocols": device.protocolStrings,
        "supportedByApp": usableProtocol(for: device) != nil,
        "isSolos": device.name.localizedCaseInsensitiveContains("solos") ||
          device.manufacturer.localizedCaseInsensitiveContains("solos") ||
          device.name.localizedCaseInsensitiveContains("kopin") ||
          device.manufacturer.localizedCaseInsensitiveContains("kopin")
      ]
    }
  }

  func pairedDevices() -> [[String: String]] {
    return candidates().map { ["name": $0.name, "address": "ea:\($0.connectionID)"] }
  }

  func handle(_ call: FlutterMethodCall, result: @escaping FlutterResult) {
    switch call.method {
    case "getPairedDevices":
      result(pairedDevices())
    case "isConnected":
      result(ready)
    case "connect":
      guard let args = call.arguments as? [String: Any],
            let address = args["address"] as? String,
            address.hasPrefix("ea:"),
            let identifier = Int(address.dropFirst(3)),
            let accessory = candidates().first(where: { $0.connectionID == identifier }) else {
        result(FlutterError(code: "IOS_ACCESSORY_NOT_FOUND", message:
          "No Solos display is available through ExternalAccessory. Bluetooth audio pairing alone is not an app data link.", details: nil))
        return
      }
      guard let proto = usableProtocol(for: accessory) else {
        result(FlutterError(code: "IOS_NO_SUPPORTED_PROTOCOL", message:
          "The connected accessory has no declared, usable MFi data protocol. Check its protocolStrings and declare an approved protocol in UISupportedExternalAccessoryProtocols before rebuilding.",
          details: ["advertised": accessory.protocolStrings, "declared": declaredProtocols]))
        return
      }
      connect(to: accessory, protocolID: proto, result: result)
    case "send":
      guard ready, let args = call.arguments as? [String: Any],
            let typed = args["bytes"] as? FlutterStandardTypedData else {
        result(FlutterError(code: "IOS_NOT_CONNECTED", message: "No open MFi accessory data stream", details: nil))
        return
      }
      let bytes = typed.data
      guard bytes.count <= 32 * 1024 else {
        result(FlutterError(code: "IMAGE_TOO_LARGE", message: "Packet is larger than the 32 KB Solos limit", details: nil))
        return
      }
      guard bytes.count >= 10 && bytes[0] == 0x1D && bytes[1] == 0x60 else {
        result(FlutterError(code: "INVALID_SOLOS_PACKET", message: "Invalid Solos frame header", details: nil))
        return
      }
      guard outgoing.count < 6 else {
        result(FlutterError(code: "TX_QUEUE_FULL", message: "Glasses data link is busy", details: nil))
        return
      }
      outgoing.append(PendingWrite(data: bytes, callback: result))
      pumpOutput()
    case "disconnect":
      closeConnection(message: "Disconnected")
      result(nil)
    default:
      result(FlutterMethodNotImplemented)
    }
  }

  private var ready: Bool {
    return session != nil && streamOpen(input?.streamStatus) && streamOpen(output?.streamStatus)
  }

  private func streamOpen(_ status: Stream.Status?) -> Bool {
    return status == .open || status == .reading || status == .writing
  }

  private func connect(to accessory: EAAccessory, protocolID: String, result: @escaping FlutterResult) {
    closeConnection(message: "Reconnecting")
    guard let newSession = EASession(accessory: accessory, forProtocol: protocolID),
          let inStream = newSession.inputStream,
          let outStream = newSession.outputStream else {
      result(FlutterError(code: "IOS_SESSION_FAILED", message:
        "iOS did not authorize an ExternalAccessory session with this protocol", details: nil))
      return
    }
    generation += 1
    let currentGeneration = generation
    session = newSession
    connectedAccessory = accessory
    input = inStream
    output = outStream
    rxBuffer.removeAll(keepingCapacity: true)
    pendingConnect = result

    inStream.delegate = self
    outStream.delegate = self
    inStream.schedule(in: .main, forMode: .common)
    outStream.schedule(in: .main, forMode: .common)
    inStream.open()
    outStream.open()
    finishConnectionIfReady()
    DispatchQueue.main.asyncAfter(deadline: .now() + 6) { [weak self] in
      guard let self = self, self.generation == currentGeneration,
            self.pendingConnect != nil else { return }
      self.closeConnection(message: "Timed out opening the accessory data streams")
    }
  }

  private func finishConnectionIfReady() {
    guard ready, let cb = pendingConnect else { return }
    pendingConnect = nil
    cb(true)
  }

  private func closeConnection(message: String) {
    generation += 1
    let error = FlutterError(code: "IOS_ACCESSORY_DISCONNECTED", message: message, details: nil)
    let connect = pendingConnect
    pendingConnect = nil
    connect?(error)
    let pending = outgoing
    outgoing.removeAll()
    for item in pending { item.callback(error) }

    if let stream = input {
      stream.delegate = nil
      stream.close()
      stream.remove(from: .main, forMode: .common)
    }
    if let stream = output {
      stream.delegate = nil
      stream.close()
      stream.remove(from: .main, forMode: .common)
    }
    input = nil
    output = nil
    session = nil
    connectedAccessory = nil
    rxBuffer.removeAll(keepingCapacity: true)
  }

  func stream(_ aStream: Stream, handle eventCode: Stream.Event) {
    switch eventCode {
    case .openCompleted:
      finishConnectionIfReady()
      pumpOutput()
    case .hasBytesAvailable:
      readAvailable()
    case .hasSpaceAvailable:
      pumpOutput()
    case .errorOccurred, .endEncountered:
      closeConnection(message: aStream.streamError?.localizedDescription ?? "Accessory stream closed")
    default:
      break
    }
  }

  private func pumpOutput() {
    guard ready, let stream = output else { return }
    while stream.hasSpaceAvailable && !outgoing.isEmpty {
      let item = outgoing[0]
      let remaining = item.data.count - item.offset
      let chunk = min(512, remaining)
      let written: Int = item.data.withUnsafeBytes { rawBytes in
        guard let base = rawBytes.baseAddress?.assumingMemoryBound(to: UInt8.self) else { return -1 }
        return stream.write(base.advanced(by: item.offset), maxLength: chunk)
      }
      if written < 0 {
        closeConnection(message: stream.streamError?.localizedDescription ?? "Accessory write failed")
        return
      }
      if written == 0 { return }
      item.offset += written
      if item.offset >= item.data.count {
        outgoing.removeFirst()
        item.callback(true)
      }
    }
  }

  private func readAvailable() {
    guard let stream = input else { return }
    var buf = [UInt8](repeating: 0, count: 4096)
    while stream.hasBytesAvailable {
      let count = stream.read(&buf, maxLength: buf.count)
      if count < 0 {
        closeConnection(message: stream.streamError?.localizedDescription ?? "Accessory read failed")
        return
      }
      if count == 0 { break }
      rxBuffer.append(contentsOf: buf.prefix(count))
      parsePackets()
    }
  }

  /// Mirror the RFCOMM packet decoder from Android SolosBluetoothPlugin.kt.
  private func parsePackets() {
    while rxBuffer.count >= 10 {
      guard rxBuffer[0] == 0x1D && rxBuffer[1] == 0x60 else {
        rxBuffer.removeFirst()
        continue
      }
      let dataLength = UInt32(rxBuffer[6]) |
        (UInt32(rxBuffer[7]) << 8) |
        (UInt32(rxBuffer[8]) << 16) |
        (UInt32(rxBuffer[9]) << 24)
      guard dataLength <= 65536 else {
        rxBuffer.removeFirst(2)
        continue
      }
      let length = Int(dataLength)
      guard rxBuffer.count >= 10 + length else { return }
      let packetType = Int(rxBuffer[2]) | (Int(rxBuffer[3]) << 8)
      let data = rxBuffer.subdata(in: 10..<(10 + length))
      sink?(["type": packetType, "payload": FlutterStandardTypedData(bytes: data)])
      rxBuffer.removeSubrange(0..<(10 + length))
    }
  }

  func onListen(withArguments arguments: Any?, eventSink events: @escaping FlutterEventSink) -> FlutterError? {
    sink = events
    return nil
  }

  func onCancel(withArguments arguments: Any?) -> FlutterError? {
    sink = nil
    return nil
  }
}